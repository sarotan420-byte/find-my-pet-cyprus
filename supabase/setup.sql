-- ---------- Tables ----------------------------------------------------

create table if not exists public.listings (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  owner_id          uuid not null default auth.uid() references auth.users(id) on delete cascade,

  -- moderation
  moderation_status text not null default 'pending'
                    check (moderation_status in ('pending','changes','approved','rejected')),
  moderator_note    text,
  reject_reason     text,
  reviewed_at       timestamptz,
  reviewed_by       uuid references auth.users(id) on delete set null,
  closed            boolean not null default false,   -- reunited / adopted / removed by owner

  -- the pet
  status       text not null check (status in ('missing','found','adoption')),
  species      text not null check (species in ('Dog','Cat','Other')),
  exotic_type  text check (char_length(exotic_type) <= 40),
  name         text check (char_length(name) <= 60),
  breed        text check (char_length(breed) <= 80),
  size         text check (size in ('Small','Medium','Large')),
  sex          text check (sex in ('Male','Female','Unknown')),
  colours      text[] not null default '{}',
  color        text check (char_length(color) <= 80),
  markings     text check (char_length(markings) <= 200),
  collar       boolean not null default false,
  chipped      boolean not null default false,

  -- where & when
  district     text not null check (district in ('Nicosia','Limassol','Larnaca','Paphos','Famagusta','Kyrenia')),
  postcode     text check (postcode ~ '^\d{4}$'),
  area         text not null check (char_length(area) between 2 and 120),
  lat          double precision not null check (lat between 34.4 and 35.8),
  lng          double precision not null check (lng between 32.2 and 34.7),
  event_date   date not null,
  event_time   text check (event_time ~ '^\d{2}:\d{2}$'),

  description  text not null check (char_length(description) between 10 and 2000),
  photos       text[] not null default '{}' check (cardinality(photos) <= 3),

  -- adoption only
  age_band     text check (age_band in ('Puppy / kitten','Young','Adult','Senior')),
  age_text     text check (char_length(age_text) <= 40),
  neutered     boolean not null default false,
  vaccinated   boolean not null default false,
  good_with    text[] not null default '{}',
  lister       text check (lister in ('Owner rehoming','Foster home','Rescue group','Shelter'))
);

create index if not exists listings_public_idx on public.listings (moderation_status, closed, status, created_at desc);
create index if not exists listings_owner_idx  on public.listings (owner_id, created_at desc);

-- Contact details live in their own table so they never appear in public listing data.
create table if not exists public.listing_contacts (
  listing_id bigint primary key references public.listings(id) on delete cascade,
  name       text not null check (char_length(name) between 1 and 80),
  phone      text not null check (char_length(phone) between 6 and 30),
  email      text check (char_length(email) <= 200)
);

create table if not exists public.moderators (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  added_at   timestamptz not null default now()
);

create table if not exists public.moderation_log (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  listing_id   bigint references public.listings(id) on delete set null,
  moderator_id uuid references auth.users(id) on delete set null,
  from_status  text,
  to_status    text,
  note         text,
  reason       text
);

create table if not exists public.saved_views (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  label      text not null check (char_length(label) between 1 and 200),
  url        text not null check (char_length(url) between 1 and 1000)
);

-- ---------- Helper ----------------------------------------------------

create or replace function public.is_moderator()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.moderators where user_id = auth.uid());
$$;

-- ---------- Row level security ---------------------------------------

alter table public.listings         enable row level security;
alter table public.listing_contacts enable row level security;
alter table public.moderators       enable row level security;
alter table public.moderation_log   enable row level security;
alter table public.saved_views      enable row level security;

drop policy if exists "read listings" on public.listings;
create policy "read listings" on public.listings for select
  using ((moderation_status = 'approved' and not closed) or owner_id = auth.uid() or public.is_moderator());

drop policy if exists "owner deletes listing" on public.listings;
create policy "owner deletes listing" on public.listings for delete
  using (owner_id = auth.uid());

drop policy if exists "read own contact" on public.listing_contacts;
create policy "read own contact" on public.listing_contacts for select
  using (public.is_moderator() or exists (select 1 from public.listings l where l.id = listing_id and l.owner_id = auth.uid()));

drop policy if exists "see own moderator row" on public.moderators;
create policy "see own moderator row" on public.moderators for select
  using (user_id = auth.uid());

drop policy if exists "moderators read log" on public.moderation_log;
create policy "moderators read log" on public.moderation_log for select
  using (public.is_moderator());

drop policy if exists "own saved views" on public.saved_views;
create policy "own saved views" on public.saved_views for all
  using (user_id = auth.uid()) with check (user_id = auth.uid());

-- Listings and contacts are only written through the functions below.
revoke insert, update on public.listings, public.listing_contacts from anon, authenticated;
revoke insert, update, delete on public.moderators, public.moderation_log from anon, authenticated;

-- ---------- Submit a listing -----------------------------------------

create or replace function public.submit_listing(p jsonb, c jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  new_id bigint;
  recent int;
  photo text;
  st text := p->>'status';
begin
  if uid is null then raise exception 'Please sign in to submit a listing.'; end if;

  select count(*) into recent from listings where owner_id = uid and created_at > now() - interval '24 hours';
  if recent >= 5 then raise exception 'You have reached the limit of 5 listings per day. Please try again tomorrow.'; end if;

  for photo in select jsonb_array_elements_text(coalesce(p->'photos', '[]'::jsonb)) loop
    if photo not like '%/storage/v1/object/public/listing-photos/' || uid::text || '/%' then
      raise exception 'Invalid photo.';
    end if;
  end loop;

  if st in ('missing','found') and (p->>'event_date')::date > current_date + 1 then
    raise exception 'The date cannot be in the future.';
  end if;

  insert into listings (owner_id, status, species, exotic_type, name, breed, size, sex, colours, color, markings,
    collar, chipped, district, postcode, area, lat, lng, event_date, event_time, description, photos,
    age_band, age_text, neutered, vaccinated, good_with, lister)
  values (uid, st, p->>'species', nullif(p->>'exotic_type',''), nullif(p->>'name',''), nullif(p->>'breed',''),
    coalesce(nullif(p->>'size',''),'Medium'), coalesce(nullif(p->>'sex',''),'Unknown'),
    coalesce(array(select jsonb_array_elements_text(p->'colours')), '{}'), nullif(p->>'color',''), nullif(p->>'markings',''),
    coalesce((p->>'collar')::boolean, false), coalesce((p->>'chipped')::boolean, false),
    p->>'district', nullif(p->>'postcode',''), p->>'area', (p->>'lat')::float8, (p->>'lng')::float8,
    (p->>'event_date')::date, nullif(p->>'event_time',''), p->>'description',
    coalesce(array(select jsonb_array_elements_text(p->'photos')), '{}'),
    case when st = 'adoption' then nullif(p->>'age_band','') end,
    case when st = 'adoption' then nullif(p->>'age_text','') end,
    coalesce((p->>'neutered')::boolean, false), coalesce((p->>'vaccinated')::boolean, false),
    case when st = 'adoption' then coalesce(array(select jsonb_array_elements_text(p->'good_with')), '{}') else '{}' end,
    case when st = 'adoption' then nullif(p->>'lister','') end)
  returning id into new_id;

  insert into listing_contacts (listing_id, name, phone, email)
  values (new_id, c->>'name', c->>'phone', nullif(c->>'email',''));

  return new_id;
end $$;

-- ---------- Show contact details (only for live listings) ------------

create or replace function public.reveal_contact(p_id bigint)
returns table (name text, phone text) language sql stable security definer set search_path = public as $$
  select c.name, c.phone
  from listing_contacts c join listings l on l.id = c.listing_id
  where c.listing_id = p_id
    and ((l.moderation_status = 'approved' and not l.closed) or l.owner_id = auth.uid() or is_moderator());
$$;

-- ---------- Owner marks a listing as reunited / adopted ---------------

create or replace function public.close_listing(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  update listings set closed = true where id = p_id and owner_id = auth.uid();
  if not found then raise exception 'Listing not found.'; end if;
end $$;

-- ---------- Moderation -----------------------------------------------

create or replace function public.moderation_queue()
returns setof jsonb language plpgsql stable security definer set search_path = public as $$
begin
  if not is_moderator() then raise exception 'Moderators only.'; end if;
  return query
    select to_jsonb(l)
      || jsonb_build_object(
           'contact_name',  c.name,
           'contact_phone', c.phone,
           'contact_email', c.email,
           'owner_created_at', u.created_at,
           'owner_is_anonymous', coalesce(u.is_anonymous, false),
           'owner_recent_count', (select count(*) from listings x where x.owner_id = l.owner_id and x.created_at > now() - interval '30 days'))
    from listings l
    left join listing_contacts c on c.listing_id = l.id
    left join auth.users u on u.id = l.owner_id
    where l.moderation_status <> 'approved' or l.created_at > now() - interval '30 days'
    order by l.created_at;
end $$;

create or replace function public.moderate_listing(p_id bigint, p_status text, p_note text default null, p_reason text default null)
returns void language plpgsql security definer set search_path = public as $$
declare old_status text;
begin
  if not is_moderator() then raise exception 'Moderators only.'; end if;
  if p_status not in ('pending','changes','approved','rejected') then raise exception 'Invalid status.'; end if;
  select moderation_status into old_status from listings where id = p_id for update;
  if not found then raise exception 'Listing not found.'; end if;
  update listings set moderation_status = p_status,
    moderator_note = nullif(p_note,''),
    reject_reason = case when p_status = 'rejected' then p_reason end,
    reviewed_at = now(), reviewed_by = auth.uid()
  where id = p_id;
  insert into moderation_log (listing_id, moderator_id, from_status, to_status, note, reason)
  values (p_id, auth.uid(), old_status, p_status, nullif(p_note,''), p_reason);
end $$;

-- Functions: signed-in users only (anonymous visitors can still reveal contacts).
revoke execute on function public.submit_listing(jsonb, jsonb), public.close_listing(bigint),
  public.moderation_queue(), public.moderate_listing(bigint, text, text, text) from public, anon;
grant execute on function public.submit_listing(jsonb, jsonb), public.close_listing(bigint),
  public.moderation_queue(), public.moderate_listing(bigint, text, text, text) to authenticated;
grant execute on function public.reveal_contact(bigint), public.is_moderator() to anon, authenticated;

-- ---------- Photo storage --------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('listing-photos', 'listing-photos', true, 5242880, array['image/webp','image/jpeg','image/png'])
on conflict (id) do nothing;

drop policy if exists "upload own listing photos" on storage.objects;
create policy "upload own listing photos" on storage.objects for insert to authenticated
  with check (bucket_id = 'listing-photos' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "delete own listing photos" on storage.objects;
create policy "delete own listing photos" on storage.objects for delete to authenticated
  using (bucket_id = 'listing-photos' and (storage.foldername(name))[1] = auth.uid()::text);
