-- =====================================================================
-- Supporters page: "Become a supporter" enquiries.
-- Anyone (including guest accounts) can send one; only moderators can read or delete them;
-- nobody can change them. Each new enquiry is emailed to every moderator through Brevo,
-- using the brevo_api_key in Vault and the notify_settings switch from notify-moderators.sql.
-- Run once in Supabase → SQL Editor (after setup.sql). Safe to run again.
-- =====================================================================

create extension if not exists pg_net;

-- Same settings table as notify-moderators.sql (created here too in case that file hasn't been run yet)
create table if not exists public.notify_settings (
  id           int primary key default 1 check (id = 1),
  enabled      boolean not null default true,
  sender_email text not null default 'noreply@findmypetcy.com',
  sender_name  text not null default 'Find My Pet Cyprus',
  site_url     text not null default 'https://www.findmypetcy.com'
);
insert into public.notify_settings (id) values (1) on conflict (id) do nothing;
alter table public.notify_settings enable row level security;

create table if not exists public.support_enquiries (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id    uuid default auth.uid() references auth.users(id) on delete set null,
  name       text not null check (char_length(btrim(name)) between 1 and 100),
  business   text check (char_length(business) <= 150),
  email      text not null check (char_length(email) <= 200 and email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  phone      text check (char_length(phone) <= 40),
  interest   text not null check (interest in ('founding', 'district', 'supporter', 'in_kind', 'other')),
  district   text check (district in ('Nicosia', 'Limassol', 'Larnaca', 'Paphos', 'Famagusta', 'Kyrenia')),
  message    text not null check (char_length(btrim(message)) between 1 and 1000),
  lang       text check (lang in ('en', 'el'))
);
alter table public.support_enquiries enable row level security;

revoke all on public.support_enquiries from anon, authenticated;
grant insert (name, business, email, phone, interest, district, message, lang) on public.support_enquiries to authenticated;
grant select, delete on public.support_enquiries to authenticated;

drop policy if exists "enquiries: anyone signed in (incl. guests) can send" on public.support_enquiries;
create policy "enquiries: anyone signed in (incl. guests) can send" on public.support_enquiries for insert to authenticated
  with check (user_id = auth.uid());
drop policy if exists "enquiries: moderators read" on public.support_enquiries;
create policy "enquiries: moderators read" on public.support_enquiries for select to authenticated using (public.is_moderator());
drop policy if exists "enquiries: moderators delete" on public.support_enquiries;
create policy "enquiries: moderators delete" on public.support_enquiries for delete to authenticated using (public.is_moderator());
-- (no update policy: nobody can change an enquiry)

-- Max 3 enquiries per account per day
create or replace function public.support_enquiries_limit() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if (select count(*) from public.support_enquiries where user_id = auth.uid() and created_at > now() - interval '24 hours') >= 3 then
    raise exception 'You have reached the limit of 3 enquiries per day. Please try again tomorrow.';
  end if;
  return new;
end $$;
drop trigger if exists support_enquiries_limit on public.support_enquiries;
create trigger support_enquiries_limit before insert on public.support_enquiries
  for each row execute function public.support_enquiries_limit();

create or replace function public.html_escape(t text) returns text language sql immutable as $$
  select replace(replace(replace(replace(t, '&', '&amp;'), '<', '&lt;'), '>', '&gt;'), '"', '&quot;');
$$;

-- Email every moderator (never blocks the enquiry if email fails)
create or replace function public.notify_moderators_new_enquiry()
returns trigger language plpgsql security definer set search_path = public, extensions as $$
declare
  s record; api_key text; recips jsonb; subj text; html text;
  label text := case new.interest when 'founding' then 'Founding Partner' when 'district' then 'District Partner'
                  when 'supporter' then 'Supporter' when 'in_kind' then 'Help in kind' else 'Something else' end;
  who text := coalesce(nullif(btrim(new.business), ''), new.name);
begin
  select * into s from public.notify_settings where id = 1;
  if not found or not s.enabled then return new; end if;
  select decrypted_secret into api_key from vault.decrypted_secrets where name = 'brevo_api_key' limit 1;
  if api_key is null or api_key = '' then return new; end if;
  select coalesce(jsonb_agg(jsonb_build_object('email', u.email)), '[]'::jsonb) into recips
  from public.moderators m join auth.users u on u.id = m.user_id where coalesce(u.email, '') <> '';
  if jsonb_array_length(recips) = 0 then return new; end if;

  subj := left(regexp_replace('New sponsorship enquiry: ' || label || ' – ' || who, '[\r\n]+', ' ', 'g'), 120);
  html := '<div style="font-family:Arial,sans-serif;max-width:560px;color:#201e1d">'
       || '<h2 style="margin:0 0 12px">New sponsorship enquiry</h2>'
       || '<table style="font-size:15px;border-collapse:collapse">'
       || '<tr><td style="padding:4px 12px 4px 0;color:#777">Interested in</td><td><b>' || label || coalesce(' · ' || new.district, '') || '</b></td></tr>'
       || '<tr><td style="padding:4px 12px 4px 0;color:#777">Name</td><td>' || public.html_escape(new.name) || '</td></tr>'
       || coalesce('<tr><td style="padding:4px 12px 4px 0;color:#777">Business</td><td>' || public.html_escape(nullif(btrim(new.business), '')) || '</td></tr>', '')
       || '<tr><td style="padding:4px 12px 4px 0;color:#777">Email</td><td>' || public.html_escape(new.email) || '</td></tr>'
       || coalesce('<tr><td style="padding:4px 12px 4px 0;color:#777">Phone</td><td>' || public.html_escape(nullif(btrim(new.phone), '')) || '</td></tr>', '')
       || '<tr><td style="padding:4px 12px 4px 0;color:#777">Language</td><td>' || case when new.lang = 'el' then 'Greek' else 'English' end || '</td></tr>'
       || '</table>'
       || '<p style="font-size:15px;white-space:pre-wrap;background:#f6f4f1;border-radius:12px;padding:14px 16px">' || public.html_escape(new.message) || '</p>'
       || '<p style="font-size:13px;color:#777">Reply to this email to answer them directly. Sent from the Supporters page on Find My Pet Cyprus.</p></div>';

  perform net.http_post(
    url := 'https://api.brevo.com/v3/smtp/email',
    headers := jsonb_build_object('api-key', api_key, 'Content-Type', 'application/json', 'accept', 'application/json'),
    body := jsonb_build_object(
      'sender', jsonb_build_object('name', s.sender_name, 'email', s.sender_email),
      'to', recips,
      'replyTo', jsonb_build_object('email', new.email, 'name', left(new.name, 100)),
      'subject', subj,
      'htmlContent', html));
  return new;
exception when others then
  return new;
end $$;
revoke execute on function public.notify_moderators_new_enquiry() from public, anon, authenticated;
drop trigger if exists notify_moderators_new_enquiry on public.support_enquiries;
create trigger notify_moderators_new_enquiry after insert on public.support_enquiries
  for each row execute function public.notify_moderators_new_enquiry();


-- "Download my data": a person's own enquiries (the table itself stays moderator-only)
create or replace function public.my_support_enquiries()
returns setof public.support_enquiries language sql stable security definer set search_path = public as $$
  select * from public.support_enquiries where user_id = auth.uid() and auth.uid() is not null order by created_at;
$$;
revoke execute on function public.my_support_enquiries() from public, anon;
grant execute on function public.my_support_enquiries() to authenticated;

