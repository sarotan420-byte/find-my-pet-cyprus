-- =====================================================================
-- "Suggest a place" on the Vets & help page.
-- Visitors suggest a new vet / shelter / rescue group or a correction;
-- only moderators can read them (Moderation page → "Place suggestions").
-- Run once in Supabase → SQL Editor (after setup.sql). Safe to run again.
-- =====================================================================

create table if not exists public.service_suggestions (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  user_id       uuid default auth.uid() references auth.users(id) on delete set null,
  kind          text not null default 'new' check (kind in ('new', 'correction')),
  name          text not null check (char_length(name) between 1 and 150),
  category      text not null default 'vet' check (category in ('vet', 'shelter', 'rescue', 'other')),
  district      text check (district in ('Nicosia', 'Limassol', 'Larnaca', 'Paphos', 'Famagusta', 'Kyrenia')),
  address       text check (char_length(address) <= 200),
  phone         text check (char_length(phone) <= 40),
  website       text check (char_length(website) <= 200),
  note          text check (char_length(note) <= 1000),
  contact_email text check (char_length(contact_email) <= 200),
  status        text not null default 'open' check (status in ('open', 'done', 'dismissed')),
  reviewed_at   timestamptz
);
alter table public.service_suggestions enable row level security;

drop policy if exists "suggest: insert own" on public.service_suggestions;
create policy "suggest: insert own" on public.service_suggestions for insert to authenticated
  with check (user_id = auth.uid() and status = 'open' and reviewed_at is null);
drop policy if exists "suggest: read own or moderator" on public.service_suggestions;
create policy "suggest: read own or moderator" on public.service_suggestions for select to authenticated
  using (user_id = auth.uid() or public.is_moderator());
drop policy if exists "suggest: moderators update" on public.service_suggestions;
create policy "suggest: moderators update" on public.service_suggestions for update to authenticated
  using (public.is_moderator()) with check (public.is_moderator());
drop policy if exists "suggest: moderators delete" on public.service_suggestions;
create policy "suggest: moderators delete" on public.service_suggestions for delete to authenticated
  using (public.is_moderator());

revoke all on public.service_suggestions from anon;
grant select, insert on public.service_suggestions to authenticated;
grant update (status, reviewed_at), delete on public.service_suggestions to authenticated;

-- Spam limit (5 per day per person) and review time stamp
create or replace function public.service_suggestions_guard() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    if (select count(*) from public.service_suggestions where user_id = auth.uid() and created_at > now() - interval '24 hours') >= 5 then
      raise exception 'You have reached the limit of 5 suggestions per day. Please try again tomorrow.';
    end if;
  elsif new.status <> old.status then
    new.reviewed_at := case when new.status = 'open' then null else now() end;
  end if;
  return new;
end $$;
drop trigger if exists service_suggestions_guard on public.service_suggestions;
create trigger service_suggestions_guard before insert or update on public.service_suggestions
  for each row execute function public.service_suggestions_guard();

-- Delete my account also deletes my suggestions (same function as in gdpr.sql)
create or replace function public.delete_my_account()
returns void language plpgsql security definer set search_path = public, auth as $$
begin
  if auth.uid() is null then raise exception 'Please sign in first.'; end if;
  if to_regclass('public.service_suggestions') is not null then
    execute 'delete from public.service_suggestions where user_id = $1' using auth.uid();
  end if;
  delete from auth.users where id = auth.uid();
end $$;
revoke execute on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;

-- Retention: suggestions are deleted 12 months after they were sent (called by the daily clean-up job)
create or replace function public.cleanup_old_suggestions()
returns int language plpgsql security definer set search_path = public as $$
declare n int;
begin
  delete from public.service_suggestions where created_at < now() - interval '12 months';
  get diagnostics n = row_count;
  return n;
end $$;
revoke execute on function public.cleanup_old_suggestions() from public, anon, authenticated;
